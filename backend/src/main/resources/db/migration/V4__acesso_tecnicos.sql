CREATE TABLE tecnicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(100) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(10) NOT NULL CHECK (perfil IN ('ADMIN', 'TECNICO')),
    equipe VARCHAR(10) NOT NULL CHECK (equipe IN ('N1', 'N2')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE sessoes (
    token_hash VARCHAR(64) PRIMARY KEY,
    tecnico_id BIGINT NOT NULL REFERENCES tecnicos(id),
    expira_em TIMESTAMP NOT NULL
);
ALTER TABLE chamados ADD COLUMN IF NOT EXISTS responsavel_id BIGINT REFERENCES tecnicos(id);
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS autor_id BIGINT REFERENCES tecnicos(id);
CREATE TABLE operacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id BIGINT NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
    autor_id BIGINT NOT NULL REFERENCES tecnicos(id),
    acao VARCHAR(40) NOT NULL,
    data_operacao TIMESTAMP NOT NULL
);
CREATE INDEX idx_operacoes_chamado ON operacoes(chamado_id, id);
