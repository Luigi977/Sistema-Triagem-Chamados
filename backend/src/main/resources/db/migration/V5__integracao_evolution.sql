-- A identidade WhatsApp não é necessariamente um número: @lid é opaco.
CREATE TABLE evolution_contatos (
    id VARCHAR(100) PRIMARY KEY,
    telefone VARCHAR(30),
    jid_preferido VARCHAR(100) NOT NULL
);
CREATE TABLE evolution_contato_jids (
    jid VARCHAR(100) PRIMARY KEY,
    contato_id VARCHAR(100) NOT NULL REFERENCES evolution_contatos(id)
);
ALTER TABLE chamados ALTER COLUMN telefone_cliente DROP NOT NULL;
ALTER TABLE chamados ADD COLUMN IF NOT EXISTS contato_whatsapp_id VARCHAR(100) REFERENCES evolution_contatos(id);
CREATE INDEX idx_chamados_contato_whatsapp ON chamados(contato_whatsapp_id, status, data_abertura);
CREATE INDEX idx_chamados_telefone_status ON chamados(telefone_cliente, status, data_abertura);

