-- Confirmar HTTP somente depois do commit; pendências sobrevivem a reinícios.
CREATE TABLE evolution_webhook_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instancia VARCHAR(80) NOT NULL,
    identificador_externo VARCHAR(255) NOT NULL,
    payload TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    tentativas INTEGER NOT NULL DEFAULT 0,
    proxima_tentativa TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recebido_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em TIMESTAMP,
    CONSTRAINT uk_evolution_inbox_externo UNIQUE(identificador_externo)
);
CREATE INDEX idx_evolution_inbox_pendente ON evolution_webhook_inbox(estado, proxima_tentativa, id);
