CREATE TABLE feedback_treinamento_ia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triagem_id BIGINT UNIQUE REFERENCES triagens_prioridade(id) ON DELETE CASCADE,
    operacao_id BIGINT UNIQUE REFERENCES operacoes(id) ON DELETE CASCADE,
    chamado_id BIGINT NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
    evento_id VARCHAR(36) NOT NULL UNIQUE,
    grupo VARCHAR(36) NOT NULL,
    payload TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDENTE' CHECK (estado IN ('PENDENTE','ENVIADO')),
    tentativas INTEGER NOT NULL DEFAULT 0,
    proxima_tentativa TIMESTAMP NOT NULL,
    criada_em TIMESTAMP NOT NULL,
    enviada_em TIMESTAMP,
    ultimo_erro VARCHAR(100),
    CHECK ((triagem_id IS NOT NULL AND operacao_id IS NULL) OR (triagem_id IS NULL AND operacao_id IS NOT NULL))
);
CREATE INDEX idx_feedback_pendente ON feedback_treinamento_ia(estado, proxima_tentativa);
