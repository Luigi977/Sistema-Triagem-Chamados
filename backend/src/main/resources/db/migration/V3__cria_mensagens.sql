CREATE TABLE IF NOT EXISTS mensagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id BIGINT NOT NULL,
    remetente VARCHAR(10) NOT NULL,
    conteudo TEXT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    data_envio TIMESTAMP(6) NOT NULL,
    identificador_externo VARCHAR(255),
    CONSTRAINT fk_mensagens_chamado FOREIGN KEY (chamado_id) REFERENCES chamados(id),
    CONSTRAINT uk_mensagens_identificador_externo UNIQUE (identificador_externo)
);
CREATE INDEX IF NOT EXISTS idx_mensagens_chamado_data ON mensagens (chamado_id, data_envio, id);
