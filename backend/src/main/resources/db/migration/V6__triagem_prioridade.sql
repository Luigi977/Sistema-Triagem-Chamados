CREATE TABLE triagens_prioridade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id BIGINT NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
    mensagem_id BIGINT REFERENCES mensagens(id) ON DELETE CASCADE,
    evento_chave VARCHAR(100) UNIQUE,
    autor_id BIGINT REFERENCES tecnicos(id),
    estado VARCHAR(30) NOT NULL CHECK (estado IN ('PROCESSANDO','AGUARDANDO_REVISAO','ACEITA','CORRIGIDA','FALHA','OBSOLETA')),
    entrada_hash VARCHAR(64) NOT NULL,
    entrada TEXT NOT NULL,
    resultado TEXT,
    erro VARCHAR(150),
    criada_em TIMESTAMP NOT NULL,
    decidida_em TIMESTAMP,
    decisor_id BIGINT REFERENCES tecnicos(id),
    prioridade_final VARCHAR(20) CHECK (prioridade_final IN ('BAIXA','MEDIA','ALTA','CRITICA')),
    justificativa VARCHAR(1000)
);
CREATE INDEX idx_triagens_chamado ON triagens_prioridade(chamado_id, id);
